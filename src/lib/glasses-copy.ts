export function glassesCopy(language: CoachLanguage): GlassesCopy {
  return COPY[language];
}

export function glassesCopyKeys(): Array<keyof GlassesCopy> {
  return Object.keys(COPY.ja) as Array<keyof GlassesCopy>;
}

export function isCoachLanguage(value: unknown): value is CoachLanguage {
  return typeof value === "string" && (COACH_LANGUAGES as readonly string[]).includes(value);
}
