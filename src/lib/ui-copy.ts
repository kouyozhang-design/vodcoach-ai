export function fillTemplate(template: string, values: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? ""));
}

export function concernFor(language: CoachLanguage, game: GameId) {
  const copy = uiCopy(language);
  return game === "valorant" ? copy.valorantConcern : copy.apexConcern;
}

export function uploadHintFor(language: CoachLanguage, game: GameId) {
  const copy = uiCopy(language);
  return game === "valorant" ? copy.valorantHint : copy.apexHint;
}

export function knownConcerns(game: GameId) {
  return (Object.keys(COPY) as CoachLanguage[]).map((language) => concernFor(language, game));
}

const KNOWN_ERRORS: Array<[string, keyof UiCopy]> = [
  [MATCH_STALL_ERROR, "stall"],
  [COACH_TIMEOUT_ERROR, "timeout"],
  [COACH_GATEWAY_ERROR, "gateway"],
  [COACH_SERVER_ERROR, "server"],
  [COACH_BAD_RESPONSE_ERROR, "badResponse"],
  [COACH_ABORTED_ERROR, "aborted"],
];

export function localizeKnownError(message: string, language: CoachLanguage) {
  const copy = uiCopy(language);
  for (const [source, key] of KNOWN_ERRORS) {
    if (message === source) return copy[key];
  }
  if (message === "このブラウザでは画面共有が使えません。PCの Chrome または Edge で開いてください。") {
    return copy.captureUnsupported;
  }
  for (const languageKey of Object.keys(COPY) as CoachLanguage[]) {
    const candidate = COPY[languageKey];
    for (const [, key] of KNOWN_ERRORS) {
      if (message === candidate[key]) return copy[key];
    }
    if (message === candidate.fileTypeError) return copy.fileTypeError;
    if (message === candidate.fileSizeError) return copy.fileSizeError;
    if (message === candidate.needInput) return copy.needInput;
    if (message === candidate.matchFailed) return copy.matchFailed;
    if (message === candidate.analyzeFailed) return copy.analyzeFailed;
    if (message === candidate.liveFailed) return copy.liveFailed;
    if (message === candidate.captureUnsupported) return copy.captureUnsupported;
    if (message === candidate.captureDenied) return copy.captureDenied;
    if (message === candidate.captureCanceled) return copy.captureCanceled;
    if (message === candidate.captureMissing) return copy.captureMissing;
    if (message === candidate.captureUnknown) return copy.captureUnknown;
    if (message === candidate.shareEnded) return copy.shareEnded;
  }
  return message;
}
